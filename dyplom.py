def air_props(T):
    Tk = T + 273.15
    rho = 101325 / (287.05 * Tk)
    mu = 1.458e-6 * Tk ** 1.5 / (Tk + 110.4)
    k = 0.0241 * (Tk / 273.15) ** 0.81
    return rho, mu / rho, k


def h_correlations(T=190.0, v=2.0):
    rho, nu, k = air_props(T)
    Pr = 0.70
    out = []
    for name, L in (("Лист 500 мм (пластина, ламінарний шар)", 0.5), ("Фланець 200 мм (пластина)", 0.2)):
        Re = v * L / nu
        out.append((name, Re, 0.664 * Re ** 0.5 * Pr ** (1 / 3) * k / L))
    Re = v * 0.04 / nu
    out.append(("Труба 40×40 (квадратний циліндр, Хільперт)", Re, 0.102 * Re ** 0.675 * Pr ** (1 / 3) * k / 0.04))
    return out


def steady_check(sp, base):
    p = dict(base, setpoint=sp, empty=True, empty_min=120)
    o = Oven(p, seed=1)
    Th_max, t_reach = 0.0, None
    while o.t < o.total_seconds():
        o.step()
        Th_max = max(Th_max, o.T_h)
    d = derived()
    q_ins = d["UA_ins"] * (o.T_w - o.t_ceh)
    q_ex = PHYS["G_exhaust"] * PHYS["cp_air"] * (o.T_a - o.t_ceh)
    L, W, H, t_i = PHYS["L"], PHYS["W"], PHYS["H"], PHYS["delta_ins"]
    A_out = 2 * ((L + 2 * t_i) * (W + 2 * t_i) + (L + 2 * t_i) * (H + 2 * t_i) + (W + 2 * t_i) * (H + 2 * t_i))
    return {"T_a": o.T_a, "T_w": o.T_w, "T_h": o.T_h, "Th_max": Th_max, "P": o.power, "q_ins": q_ins, "q_ex": q_ex,
            "T_skin": o.t_ceh + q_ins / A_out / 10.0, "A_out": A_out, "eb": o.energy_balance()}


def contact_table():
    rows = []
    spot = dict(MEAS, d_pad=0.0011, h_contact=2000.0, h_pad=1e-9)
    rows.append(("Оболонка Ø1,5 притиснута без площадки (пляма ≈1 мм², h_к = 2000)", contact_beta(190, spot)))
    for dp in (0.006, 0.010, 0.015):
        for hc in (500.0, 1000.0, 3000.0):
            mark = " ← базовий" if (dp, hc) == (MEAS["d_pad"], MEAS["h_contact"]) else ""
            rows.append((f"Площадка Ø{dp * 1000:.0f} мм, h_к = {hc:.0f} Вт/(м²·К){mark}",
                         contact_beta(190, dict(MEAS, d_pad=dp, h_contact=hc))))
    return rows


def hc_for_beta(beta, d_pad=0.010):
    """h_к, за якого площадка d_pad дає заданий β (бісекція)."""
    lo, hi = 50.0, 20000.0
    for _ in range(60):
        mid = (lo * hi) ** 0.5
        if contact_beta(190, dict(MEAS, d_pad=d_pad, h_contact=mid)) > beta:
            lo = mid
        else:
            hi = mid
    return mid


def dT_env_for(a, T):
    lo, hi = 0.0, 50.0
    for _ in range(60):
        mid = (lo + hi) / 2
        if abs(radiation_error(T, T - mid)) < a:
            lo = mid
        else:
            hi = mid
    return mid


