"""Термопара типу K: функції NIST ITS-90 (EN/IEC 60584-1). E у мВ, t у °C."""
import math

# Пряма функція, діапазон 0…1372 °C
_C = [-0.176004136860e-01, 0.389212049750e-01, 0.185587700320e-04, -0.994575928740e-07,
      0.318409457190e-09, -0.560728448890e-12, 0.560750590590e-15, -0.320207200030e-18,
      0.971511471520e-22, -0.121047212750e-25]
_A0, _A1, _A2 = 0.118597600000e+00, -0.118343200000e-03, 0.126968600000e+03
# Пряма функція, діапазон −270…0 °C
_CN = [0.0, 0.394501280250e-01, 0.236223735980e-04, -0.328589067840e-06, -0.499048287770e-08,
       -0.675090591730e-10, -0.574103274280e-12, -0.310888728940e-14, -0.104516093650e-16,
       -0.198892668780e-19, -0.163226974860e-22]

# Класс допуску 1 (IEC 60584-1): ±1,5 °C або ±0,004·|t|
CLASS1 = lambda t: max(1.5, 0.004 * abs(t))


def emf(t):
    """ТЕРС, мВ, при вільних кінцях 0 °C."""
    if t >= 0:
        e = sum(c * t ** i for i, c in enumerate(_C))
        return e + _A0 * math.exp(_A1 * (t - _A2) ** 2)
    return sum(c * t ** i for i, c in enumerate(_CN))


def demf(t):
    """Чутливість dE/dt, мВ/°C (чисельно)."""
    h = 0.01
    return (emf(t + h) - emf(t - h)) / (2 * h)


def temp(e, guess=25.0):
    """Обернена функція: температура за ТЕРС (метод Ньютона, похибка < 1e-6 °C)."""
    t = guess
    for _ in range(30):
        dt = (emf(t) - e) / demf(t)
        t -= dt
        if abs(dt) < 1e-7:
            break
    return t
